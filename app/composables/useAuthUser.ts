/**
 * @module app/composables/useAuthUser
 * @fileoverview Реактивное состояние для хранения текущего авторизованного пользователя.
 * @description
 * Этот модуль предоставляет composable `useAuthUser` для работы с текущим пользователем
 * во Vue/Nuxt приложении. Состояние хранится глобально через `useState` и доступно
 * во всех компонентах и middleware.
 * ---
 * ### Логика работы:
 * 1. Создается реактивное состояние `currentUser` с помощью `useState`.
 * 2. По умолчанию значение `null` (пользователь не авторизован).
 * 3. При успешной авторизации или загрузке сессии значение обновляется объектом `User`.
 *
 * ### Особенности:
 * - Реактивное состояние доступно глобально в приложении.
 * - Поддерживает типизацию через `User` из Lucia.
 * - Используется для синхронизации состояния пользователя между middleware и компонентами.
 *
 * ### Применение:
 * - Проверка авторизации в компонентах.
 * - Инициализация состояния пользователя в middleware (`auth.global.ts`).
 * - Доступ к текущему пользователю для UI и API запросов.
 */

import type { User } from 'lucia';
import type { Ref } from 'vue';

import { useState } from 'nuxt/app';

export function useAuthUser(): Ref<User | null> {
	return useState<User | null>('currentUser', () => null);
}
